#!/usr/bin/env node
// Paketon kodin lokal të reports në një entrypoint të vetëm për mjete që pranojnë
// vetëm një skedar. Varësitë npm deklarohen statikisht për bundler-in e Supabase;
// logjika e raportit është brenda skedarit dhe nuk shkarkohet nga GitHub.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, constants } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(await readFile(resolve(root, "supabase/functions/reports/deno.json"), "utf8"));
const imports = config.imports;
const names = ["@supabase/supabase-js", "jszip", "pdf-lib"];
for (const name of names) {
  if (!/^npm:.+@\d+\.\d+\.\d+$/.test(imports[name] || "")) {
    throw new Error(`Kërkohet version npm i fiksuar për ${name}`);
  }
}

const built = await build({
  absWorkingDir: root,
  entryPoints: ["supabase/functions/reports/index.ts"],
  bundle: true, minify: true, write: false,
  platform: "neutral", format: "esm", target: "es2022",
  plugins: [{
    name: "pinned-npm",
    setup(b) {
      b.onResolve({ filter: /^(?:@supabase\/supabase-js|jszip|pdf-lib)$/ }, (args) => ({ path: imports[args.path], external: true }));
    },
  }],
});
const bundle = Buffer.from(built.outputFiles[0].contents);
const sha = createHash("sha256").update(bundle).digest("hex");
const payload = brotliCompressSync(bundle, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).toString("base64");
const body = `// Generated by scripts/package-reports.mjs; bundled reports SHA-256: ${sha}\n` +
  `import { brotliDecompressSync } from "node:zlib";\n` +
  `import { Buffer } from "node:buffer";\n` +
  names.map((name) => `import ${JSON.stringify(imports[name])};\n`).join("") +
  `const payload = ${JSON.stringify(payload)};\n` +
  `const code = brotliDecompressSync(Buffer.from(payload, "base64"));\n` +
  `const digest = Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", code)), (n) => n.toString(16).padStart(2, "0")).join("");\n` +
  `if (digest !== ${JSON.stringify(sha)}) throw new Error("Reports bundle integrity check failed");\n` +
  `await import("data:application/javascript;base64," + code.toString("base64"));\n`;

const output = resolve(root, process.argv[2] || "out/reports/index.ts");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, body);
console.log(`Reports bundle: ${bundle.length} bytes, SHA-256 ${sha}`);
console.log(`Deployable entrypoint: ${output} (${Buffer.byteLength(body)} bytes)`);
